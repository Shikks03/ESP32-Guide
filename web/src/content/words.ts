/** Intro words first, then each track's. Tracks were written in parallel, so a few ids
 * (struct, strcmp, snprintf, pragma-once, has-include, …) exist in more than one list: first one wins. */
export const WORDS: Word[] = [...BASE_WORDS, ...WORDS_WIFI, ...WORDS_RADAR, ...WORDS_BULB].filter(
  (w, i, all) => all.findIndex((x) => x.id === w.id) === i,
);

export const wordById = (id: string): Word | undefined => WORDS.find((w) => w.id === id);
