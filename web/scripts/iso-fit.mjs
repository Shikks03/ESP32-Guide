// Measures every illustrated icon in headless Chrome and writes src/components/iso/fit.ts,
// the table IsoIcon uses to centre each drawing and scale it to fill its tile.
// Run from web/ after changing art.tsx:  node scripts/iso-fit.mjs
// Chrome is found via the CHROME env var, else the default Windows install path.
import { createServer } from 'vite';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const chrome = process.env.CHROME ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const require = createRequire(path.join(web, 'package.json'));
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');

const TARGET = 56; // the drawing's longer side, in 64-unit canvas units
const K_MIN = 1;
const K_MAX = 1.5;
const PX = 640; // measuring size: 10 px per canvas unit

const server = await createServer({ root: web, server: { middlewareMode: true, hmr: false, watch: null }, appType: 'custom', logLevel: 'error', optimizeDeps: { noDiscovery: true } });
let html;
try {
  const art = await server.ssrLoadModule('/src/components/iso/art.tsx');
  const h = React.createElement;
  const sets = { lesson: art.LESSON_ART, part: art.PART_ART, hotspot: art.HOTSPOT_ART, track: art.TRACK_ART, family: art.FAMILY_ART, fallback: { _: art.FALLBACK_ART } };
  const body = renderToStaticMarkup(
    h('div', null, Object.entries(sets).flatMap(([set, items]) =>
      Object.entries(items).map(([id, node]) => h('svg', { key: `${set}/${id}`, 'data-key': `${set}/${id}`, width: PX, height: PX, viewBox: '0 0 64 64' }, node)))),
  );
  const css = readFileSync(path.join(web, 'src/components/iso/iso.css'), 'utf8');
  // Glows are light, not mass: they are left out of the measurement.
  const script = `
    const out = {};
    for (const svg of document.querySelectorAll('svg')) {
      const o = svg.getBoundingClientRect();
      let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
      for (const el of svg.querySelectorAll('path,circle,ellipse')) {
        if (el.closest('.iso-glow')) continue;
        const r = el.getBoundingClientRect();
        x0 = Math.min(x0, r.left - o.left); y0 = Math.min(y0, r.top - o.top);
        x1 = Math.max(x1, r.right - o.left); y1 = Math.max(y1, r.bottom - o.top);
      }
      out[svg.dataset.key] = [x0, y0, x1, y1].map((v) => v / ${PX / 64});
    }
    document.body.innerHTML = '<pre id="out">' + JSON.stringify(out) + '</pre>';`;
  html = `<!doctype html><meta charset="utf-8"><style>${css} svg{display:block}</style>${body}<script>${script}</script>`;
} finally {
  await server.close();
}

const file = path.join(mkdtempSync(path.join(tmpdir(), 'iso-fit-')), 'measure.html');
writeFileSync(file, html);
const dom = execFileSync(chrome, ['--headless=new', '--disable-gpu', '--virtual-time-budget=3000', '--dump-dom', pathToFileURL(file).href], { encoding: 'utf8', maxBuffer: 64 << 20, stdio: ['ignore', 'pipe', 'ignore'] });
const boxes = JSON.parse(dom.match(/<pre id="out">(.*?)<\/pre>/s)[1].replaceAll('&quot;', '"'));

const r2 = (n) => Math.round(n * 100) / 100;
const table = {};
for (const [key, [x0, y0, x1, y1]] of Object.entries(boxes)) {
  const [set, id] = key.split('/');
  const k = Math.min(K_MAX, Math.max(K_MIN, TARGET / Math.max(x1 - x0, y1 - y0)));
  (table[set] ??= {})[id] = [r2((x0 + x1) / 2), r2((y0 + y1) / 2), r2(k)];
}
const lines = Object.entries(table).map(([set, items]) =>
  `  ${set}: {\n${Object.entries(items).map(([id, v]) => `    ${JSON.stringify(id)}: [${v.join(', ')}],`).join('\n')}\n  },`);
writeFileSync(
  path.join(web, 'src/components/iso/fit.ts'),
  `// Generated by scripts/iso-fit.mjs. Do not edit by hand; rerun the script after changing art.tsx.\n// Per drawing: [centre x, centre y, scale] measured on the 64-unit canvas, glows excluded.\nexport type Fit = [number, number, number];\n\nexport const FIT: Record<string, Record<string, Fit>> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`fit.ts written: ${Object.keys(boxes).length} drawings`);
